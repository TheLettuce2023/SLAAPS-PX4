"""Independent MAVLink 2 signing vectors for the private C1E parser tests.

The payload is packed from the frozen W1 field order.  CRC and SHA-256 are
calculated with Python's standard library; no generated MAVLink encoder or
signing helper produces these frames.  Keys and identities here are disposable
fixture values, never native bootstrap material.
"""

from __future__ import annotations

import hashlib
import struct
import sys
from pathlib import Path


WIRE_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(WIRE_DIR))
import test_generated_mavlink as wire_fixture  # noqa: E402


KEY = bytes(range(1, 33))
REQUEST_ID = 200010
CRC_EXTRA = wire_fixture.crc_extra(
    "RESEARCH_DIAGNOSTIC_REQUEST",
    wire_fixture.FIELDS["RESEARCH_DIAGNOSTIC_REQUEST"],
)
REQUEST_FORMAT = "<10Q3fI8B4s"
CHANNEL = 3
TIMESTAMP = 10_000_100


def x25(data: bytes) -> int:
    crc = 0xFFFF
    for byte in data:
        value = byte ^ (crc & 0xFF)
        value ^= (value << 4) & 0xFF
        crc = ((crc >> 8) ^ (value << 8) ^ (value << 3) ^ (value >> 4)) & 0xFFFF
    return crc


def payload() -> bytearray:
    return bytearray(struct.pack(
        REQUEST_FORMAT,
        11, 12, 13, 14, 15, 16, 17, 100, 180, 0,
        1.5, -2.25, 0.5, 0x10000,
        1, 1, 1, 1, 1, 1, 1, 0, b"\0\0\0\0",
    ))


def frame(
    body: bytes,
    *,
    timestamp: int = TIMESTAMP,
    key: bytes = KEY,
    link: int = 7,
    system: int = 42,
    component: int = 191,
    message_id: int = REQUEST_ID,
    extra: int = CRC_EXTRA,
    signed: bool = True,
    incompat: int | None = None,
    compat: int = 0,
) -> bytes:
    if incompat is None:
        incompat = 1 if signed else 0
    header = bytes((0xFD, len(body), incompat, compat, 17, system, component))
    header += message_id.to_bytes(3, "little")
    crc = x25(header[1:] + body + bytes((extra,))).to_bytes(2, "little")
    packet = header + body + crc
    if signed:
        stamp = bytes((link,)) + timestamp.to_bytes(6, "little")
        packet += stamp + hashlib.sha256(key + packet + stamp).digest()[:6]
    return packet


def changed(offset: int, value: int, *, timestamp: int = TIMESTAMP) -> bytes:
    body = payload()
    body[offset] = value
    return frame(body.rstrip(b"\0"), timestamp=timestamp)


def vectors() -> dict[str, bytes]:
    body = payload()
    trimmed = bytes(body).rstrip(b"\0")
    valid = frame(trimmed)
    bad_crc = bytearray(valid)
    bad_crc[10] ^= 0x01
    bad_signature = bytearray(valid)
    bad_signature[-1] ^= 0x01
    high_bad_signature = bytearray(frame(trimmed, timestamp=TIMESTAMP + 999_999))
    high_bad_signature[-1] ^= 0x01
    wrong_key = bytes((KEY[0] ^ 1,)) + KEY[1:]
    return {
        "valid": valid,
        "valid_full": frame(body),
        "valid_next": frame(trimmed, timestamp=TIMESTAMP + 1),
        "valid_old": frame(trimmed, timestamp=TIMESTAMP - 1),
        "high_bad_signature": bytes(high_bad_signature),
        "bad_signature": bytes(bad_signature),
        "bad_crc": bytes(bad_crc),
        "wrong_key": frame(trimmed, key=wrong_key),
        "unsigned_frame": frame(trimmed, signed=False),
        "wrong_link": frame(trimmed, link=9),
        "wrong_system": frame(trimmed, system=43),
        "wrong_component": frame(trimmed, component=192),
        "wrong_run": changed(0, 99),
        "wrong_owner": changed(8, 99),
        "wrong_controller": changed(16, 99),
        "wrong_source": changed(24, 99),
        "wrong_transport": changed(32, 99),
        "wrong_target": changed(98, 2),
        "wrong_target_component": changed(99, 2),
        "wrong_map": changed(72, 1),
        "zero_transition": changed(48, 0),
        "wrong_domain": changed(96, 2),
        "wrong_flags": changed(103, 1),
        "wrong_reserved": changed(104, 1),
        "nonfinite_acceleration": frame(
            bytes(body[:88] + struct.pack("<f", float("nan")) + body[92:]).rstrip(b"\0")
        ),
        "unsupported_compat": frame(trimmed, compat=1),
        "unsupported_incompat": frame(trimmed, incompat=3),
        "wrong_message": frame(trimmed, message_id=200011, extra=wire_fixture.crc_extra(
            "RESEARCH_DIAGNOSTIC_STATUS",
            wire_fixture.FIELDS["RESEARCH_DIAGNOSTIC_STATUS"],
        )),
        "truncated": valid[:-1],
        "trailing": valid + b"\0",
        "concatenated": valid + valid,
        "split_prefix": valid[:len(valid) // 2],
        "split_suffix": valid[len(valid) // 2:],
        "mavlink1": bytes((0xFE,)) + valid[1:],
    }


def write_cpp_header(path: Path) -> None:
    lines = ["// Generated by independent_vectors.py. Disposable fixture bytes.",
             "#pragma once", "namespace independent_vectors {"]
    for name, data in vectors().items():
        lines.append(f'inline constexpr const char *{name} = "{data.hex()}";')
    lines.append("} // namespace independent_vectors")
    path.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: independent_vectors.py HEADER")
    write_cpp_header(Path(sys.argv[1]))
